# shellcheck shell=bash
# geodatalab — container backend (Podman preferred, Docker fallback).
# Sourced by geodatalab.sh. Implements container_<op> for the be() dispatcher.

COMPOSE_FILE="${SCRIPT_DIR}/compose.yml"
COMPOSE_DATA_FILE=""      # per instance, see container_apply_instance
CONTAINER_NAME=""
COMPOSE_PROJECT=""
SERVICE_NAME="gis"
UV_IMAGE="ghcr.io/astral-sh/uv:python${GDL_PYTHON}-trixie-slim"

RUNTIME=""
COMPOSE=""

# IMAGE_TAG stores the full tag suffix, e.g. "2025.06-lab" or "latest" or "".
# Empty / "latest" both resolve to geodatalab:latest (backward-compatible).
get_image_name() {
    echo "geodatalab:${IMAGE_TAG:-latest}"
}

detect_runtime() {
    [[ -n "$RUNTIME" ]] && return
    if command -v podman &>/dev/null; then
        RUNTIME="podman"
        if podman compose version &>/dev/null; then
            COMPOSE="podman compose"
        elif command -v podman-compose &>/dev/null; then
            COMPOSE="podman-compose"
        else
            error "podman found but no compose. Install: dnf install podman-compose"
            exit 1
        fi
    elif command -v docker &>/dev/null; then
        RUNTIME="docker"
        if docker compose version &>/dev/null; then
            COMPOSE="docker compose"
        elif command -v docker-compose &>/dev/null; then
            COMPOSE="docker-compose"
        else
            error "docker found but no compose plugin."
            exit 1
        fi
    else
        error "No container runtime found. Install podman or docker,"
        echo  "  or switch backend:  $0 backend pixi" >&2
        exit 1
    fi
}

container_init() { detect_runtime; }

# Per-instance names: default → geodatalab, instance foo → geodatalab-foo
container_apply_instance() {
    CONTAINER_NAME="$GDL_NAME"
    COMPOSE_PROJECT="$GDL_NAME"
    COMPOSE_DATA_FILE="${GDL_STATE_DIR}/compose.data.yml"
}

# ── Data folders → compose fragment ────────────────────────────────────────────

_yq() {  # quote a string for YAML double-quoted scalars
    local s="${1//\\/\\\\}"
    printf '"%s"' "${s//\"/\\\"}"
}

# Render .gdl/<instance>/compose.data.yml from the config. Always regenerated.
container_render_data() {
    mkdir -p "$GDL_STATE_DIR"
    local e
    {
        echo "# GENERATED by geodatalab.sh for instance '${GDL_INSTANCE}' — do not edit, changes are overwritten."
        echo "# Manage with: ./geodatalab.sh data add|rm|open   and   ./geodatalab.sh limits"
        echo "# Self-contained (no \${VAR} interpolation needed), so VS Code Dev Containers"
        echo "# can use it directly — see .devcontainer/devcontainer.json."
        echo "services:"
        echo "  ${SERVICE_NAME}:"
        echo "    image: $(_yq "$(get_image_name)")"
        echo "    container_name: $(_yq "$CONTAINER_NAME")"
        echo "    labels:"
        echo "      - $(_yq "io.geodatalab.checkout=${SCRIPT_DIR}")"
        echo "      - $(_yq "io.geodatalab.instance=${GDL_INSTANCE}")"
        echo "    environment:"
        echo "      - $(_yq "GDL_MODE=${GDL_MODE:-lab}")"
        echo "      - $(_yq "GDL_OPEN=${GDL_OPEN:-}")"
        echo "      - $(_yq "GDL_PROFILE=${PROFILE:-lab}")"
        echo "      - $(_yq "GDL_BACKEND=container")"
        echo "      - $(_yq "GDL_INSTANCE=${GDL_INSTANCE}")"
        for e in "${GDL_DATA_DIRS[@]+"${GDL_DATA_DIRS[@]}"}"; do
            _data_parse "$e"
            echo "      - $(_yq "$(gdl_data_var "$_D_NAME")=/gdl/data/${_D_NAME}")"
        done
        if [[ -n "${WORKSPACE:-}" || ${#GDL_DATA_DIRS[@]} -gt 0 ]]; then
            echo "    volumes:"
            # Same target as compose.yml → this entry replaces the interpolated one.
            [[ -n "${WORKSPACE:-}" ]] && echo "      - $(_yq "${WORKSPACE}:/gdl/workspace:Z")"
            for e in "${GDL_DATA_DIRS[@]+"${GDL_DATA_DIRS[@]}"}"; do
                _data_parse "$e"
                # No :Z relabel — label=disable in compose.yml already covers SELinux,
                # and relabelling large external data disks is slow and invasive.
                echo "      - $(_yq "${_D_PATH}:/gdl/data/${_D_NAME}$([[ $_D_RO -eq 1 ]] && echo ':ro' || true)")"
            done
        fi
        if [[ -n "${GDL_MEMORY}${GDL_CPUS}${GDL_MEMORY_RESERVE}" ]]; then
            echo "    deploy:"
            echo "      resources:"
            if [[ -n "${GDL_MEMORY}${GDL_CPUS}" ]]; then
                echo "        limits:"
                [[ -n "$GDL_MEMORY" ]] && echo "          memory: $(_yq "$GDL_MEMORY")"
                [[ -n "$GDL_CPUS" ]]   && echo "          cpus: $(_yq "$GDL_CPUS")"
            fi
            if [[ -n "$GDL_MEMORY_RESERVE" ]]; then
                echo "        reservations:"
                echo "          memory: $(_yq "$GDL_MEMORY_RESERVE")"
            fi
        fi
    } > "$COMPOSE_DATA_FILE"
}

compose_run() {
    container_render_data
    WORKSPACE="${WORKSPACE:-.}" \
        PROFILE="${PROFILE:-lab}" \
        GDL_MODE="${GDL_MODE:-lab}" \
        GDL_TAG="${IMAGE_TAG:-latest}" \
        GDL_PORT="${GDL_PORT:-8888}" \
        $COMPOSE -p "$COMPOSE_PROJECT" -f "$COMPOSE_FILE" -f "$COMPOSE_DATA_FILE" "$@"
}

# Owner checkout of container $CONTAINER_NAME: path, "" (no label = legacy/foreign) or "none"
_container_owner() {
    $RUNTIME inspect -f '{{index .Config.Labels "io.geodatalab.checkout"}}' "$CONTAINER_NAME" 2>/dev/null \
        | sed 's/<no value>//' || echo none
}

# Running AND created by this checkout (containers of other checkouts don't count)
container_is_running() {
    detect_runtime
    [[ "$($RUNTIME inspect -f '{{.State.Running}}' "$CONTAINER_NAME" 2>/dev/null || echo false)" == "true" ]] \
        && [[ "$(_container_owner)" == "$SCRIPT_DIR" ]]
}

# Refuse to touch a same-named container that belongs to another checkout
_container_guard_foreign() {
    $RUNTIME container exists "$CONTAINER_NAME" 2>/dev/null \
        || $RUNTIME inspect "$CONTAINER_NAME" &>/dev/null || return 0
    local owner; owner="$(_container_owner)"
    [[ "$owner" == "$SCRIPT_DIR" ]] && return 0
    error "A container named '${CONTAINER_NAME}' already exists and belongs to ${owner:-another (older) geodatalab checkout}."
    echo  "  Use a separate instance here:  $0 instances new <name>   (container geodatalab-<name>)" >&2
    exit 1
}

container_health() {
    $RUNTIME inspect -f '{{.State.Health.Status}}' "$CONTAINER_NAME" 2>/dev/null || echo ""
}

container_label() { get_image_name; }

# Poll for container health instead of sleeping a fixed amount.
# In idle mode (no Jupyter) just waits for the running state.
_wait_healthy() {
    local timeout=60 elapsed=0 status

    if [[ "${GDL_MODE:-lab}" == "idle" ]]; then
        printf "  Waiting for container"
        while ! container_is_running && [[ $elapsed -lt $timeout ]]; do
            printf "."; sleep 1; elapsed=$((elapsed+1))
        done
        echo ""
        return 0
    fi

    printf "  Waiting for Jupyter"
    while [[ $elapsed -lt $timeout ]]; do
        status=$(container_health)
        case "$status" in
            healthy)   echo " ready."; return 0 ;;
            unhealthy) echo " unhealthy."; warn "Check logs: $0 logs"; return 1 ;;
        esac
        printf "."; sleep 2; elapsed=$((elapsed+2))
    done
    echo ""
    warn "Still starting — check: $0 logs"
    return 0
}

# ── Images ─────────────────────────────────────────────────────────────────────

container_images() {
    heading "geodatalab images"
    local active="${IMAGE_TAG:-latest}" found=0 tag size created_rest

    while IFS=' ' read -r tag size created_rest; do
        [[ -z "$tag" ]] && continue
        found=1
        if [[ "$tag" == "$active" ]]; then
            echo -e "  ${GREEN}${BOLD}* ${tag}${NC}${GREEN}  ${size}  (${created_rest})${NC}"
        else
            echo    "    ${tag}  ${size}  (${created_rest})"
        fi
    done < <($RUNTIME images --filter "reference=geodatalab" \
        --format "{{.Tag}} {{.Size}} {{.CreatedSince}}" 2>/dev/null \
        | sort -t'-' -k1,1Vr || true)

    [[ $found -eq 0 ]] && echo "  None found."
    echo ""
    echo -e "  Active: ${BLUE}geodatalab:${active}${NC}"
    echo    "  Switch: $0 use <tag>"
}

container_use() {
    local tag="${1:-}" p
    if [[ -z "$tag" ]]; then
        container_images
        echo ""
        read -rp "  Tag to activate: " tag
        [[ -z "$tag" ]] && return 0
    fi
    IMAGE_TAG="$tag"
    # Sync PROFILE if the tag encodes a known profile suffix
    for p in "${PROFILES[@]}"; do
        if [[ "$tag" == *"-${p}" ]]; then PROFILE="$p"; break; fi
    done
    save_config
    info "Active image: geodatalab:${IMAGE_TAG}"
    info "Profile: ${PROFILE}"
}

# ── Build ──────────────────────────────────────────────────────────────────────

container_build() {
    local build_profile="${PROFILE:-lab}" build_tag="" extra_args=()

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --profile|-p)
                shift
                if ! validate_profile "${1:-}"; then
                    error "Invalid profile: ${1:-}  (valid: ${PROFILES[*]})"
                    exit 1
                fi
                build_profile="$1"; shift ;;
            --tag|-t)  shift; build_tag="${1:-}"; shift ;;
            --no-cache) extra_args+=("--no-cache"); shift ;;
            *) extra_args+=("$1"); shift ;;
        esac
    done

    [[ -z "$build_tag" ]] && build_tag="$(date +%Y.%m)"
    local versioned_tag="${build_tag}-${build_profile}"
    local versioned_image="geodatalab:${versioned_tag}"

    if [[ ! -f "${SCRIPT_DIR}/requirements/locks/${build_profile}.lock" ]]; then
        warn "No lock file for '${build_profile}' — the build will resolve the latest versions."
        echo "  Pin them first with:  $0 lock ${build_profile}"
    fi

    info "Building  [profile: ${build_profile}, tag: ${versioned_tag}]..."
    PROFILE="$build_profile" IMAGE_TAG="$versioned_tag" \
        compose_run build "${extra_args[@]+"${extra_args[@]}"}"

    if $RUNTIME tag "$versioned_image" "geodatalab:latest" 2>/dev/null; then
        info "Tagged as geodatalab:latest"
    fi

    IMAGE_TAG="$versioned_tag"
    PROFILE="$build_profile"
    save_config

    info "Build complete: ${versioned_image}"
    $RUNTIME images --filter "reference=geodatalab" \
        --format "  {{.Tag}}  {{.Size}}" 2>/dev/null | head -8 || true
}

# ── Lock (pip, for the image) ──────────────────────────────────────────────────
# requirements/locks/<profile>.lock — exact versions for the image's Python
# (debian:trixie → $GDL_PYTHON) and architecture. Uses host uv if present,
# otherwise the official uv image (no host install needed).

_uv() {
    if command -v uv &>/dev/null; then
        (cd "$SCRIPT_DIR" && uv "$@")
    else
        local user_args=()
        [[ "$RUNTIME" == "docker" ]] && user_args=(--user "$(id -u):$(id -g)")
        mkdir -p "$GDL_STATE_ROOT/uv-cache"
        $RUNTIME run --rm "${user_args[@]+"${user_args[@]}"}" \
            -v "${SCRIPT_DIR}:/src:Z" -w /src \
            -e UV_CACHE_DIR=/src/.gdl/uv-cache \
            "$UV_IMAGE" uv "$@"
    fi
}

container_lock() {
    local p arch
    arch="$(uname -m)"; [[ "$arch" == "arm64" ]] && arch="aarch64"
    mkdir -p "${SCRIPT_DIR}/requirements/locks"
    for p in "$@"; do
        info "Locking ${p}  [python ${GDL_PYTHON}, ${arch}-manylinux_2_28]..."
        _uv pip compile --quiet \
            "requirements/${p}.txt" requirements/build.txt \
            --python-version "$GDL_PYTHON" \
            --python-platform "${arch}-manylinux_2_28" \
            --custom-compile-command "./geodatalab.sh lock ${p}" \
            -o "requirements/locks/${p}.lock"
        info "Wrote requirements/locks/${p}.lock  ($(grep -c '==' "${SCRIPT_DIR}/requirements/locks/${p}.lock") packages)"
    done
    echo "  Rebuild to apply:  $0 build"
}

# ── Lifecycle ──────────────────────────────────────────────────────────────────

container_start() {
    ensure_workspace

    if container_is_running; then
        warn "Already running."
        return 0
    fi
    _container_guard_foreign

    local image
    image=$(get_image_name)
    if ! $RUNTIME inspect --type image "$image" &>/dev/null; then
        if [[ "${IMAGE_TAG:-latest}" != "latest" ]] && \
           $RUNTIME inspect --type image "geodatalab:latest" &>/dev/null; then
            warn "Image ${image} not found — falling back to geodatalab:latest"
            IMAGE_TAG="latest"
            image="geodatalab:latest"
        else
            error "Image not found: ${image}"
            echo  "  Build it:  $0 build --profile ${PROFILE:-lab}"
            exit 1
        fi
    fi

    info "Starting  [image: ${image}, mode: ${GDL_MODE:-lab}, port: ${GDL_PORT:-8888}]..."
    compose_run up -d
    echo ""
    _wait_healthy
}

container_stop() {
    _container_guard_foreign
    info "Stopping container..."
    compose_run stop
    info "Stopped."
}

container_exec() {
    if ! container_is_running; then
        error "Container not running. Start it first: $0 start"
        exit 1
    fi
    if [[ $# -eq 0 ]]; then
        $RUNTIME exec -it "$CONTAINER_NAME" bash
    else
        $RUNTIME exec -it "$CONTAINER_NAME" "$@"
    fi
}

container_logs() { compose_run logs -f "$SERVICE_NAME"; }

container_url_token() {
    container_is_running || return 0
    $RUNTIME logs "$CONTAINER_NAME" 2>&1 \
        | grep -oP '(?<=token=)[a-f0-9]+' | tail -1 || true
}

container_status() {
    heading "Container"
    if container_is_running; then
        echo -e "  State:    ${GREEN}running${NC}"
        echo    "  Health:   $(container_health)"
        echo    "  Started:  $($RUNTIME inspect -f '{{.State.StartedAt}}' "$CONTAINER_NAME" 2>/dev/null || echo n/a)"
    else
        echo -e "  State:    ${RED}stopped${NC}"
    fi
    echo    "  Runtime:  ${RUNTIME} (${COMPOSE})"
    echo    "  Image:    $(get_image_name)"

    heading "Images"
    $RUNTIME images --filter "reference=geodatalab" \
        --format "  {{.Tag}}  {{.Size}}  (created {{.CreatedSince}})" \
        2>/dev/null || echo "  None built yet."
}

# ── Clean / Update ─────────────────────────────────────────────────────────────

container_clean() {
    local images ids
    _container_guard_foreign
    echo -e "${YELLOW}This will remove the container of instance '${GDL_INSTANCE}' (${CONTAINER_NAME}).${NC}"
    if confirm "Remove it?" N; then
        compose_run down --volumes 2>/dev/null || true
        info "Container removed."
    else
        info "Cancelled."; return 0
    fi
    images=$($RUNTIME images --filter "reference=geodatalab" \
        --format "  {{.Tag}}  {{.Size}}" 2>/dev/null)
    [[ -z "$images" ]] && return 0
    echo ""
    echo -e "${YELLOW}geodatalab images (shared by ALL instances):${NC}"
    echo "$images"
    if confirm "Also remove all of these images?" N; then
        ids=$($RUNTIME images --filter "reference=geodatalab" --format "{{.ID}}" \
            2>/dev/null | sort -u)
        # shellcheck disable=SC2086
        [[ -n "$ids" ]] && $RUNTIME rmi --force $ids 2>/dev/null || true
        IMAGE_TAG=""
        save_config
        info "Images removed."
    fi
}

container_update() {
    local versioned_tag
    versioned_tag="$(date +%Y.%m)-${PROFILE:-lab}"
    info "Rebuilding image (no cache)  [tag: ${versioned_tag}]..."
    IMAGE_TAG="$versioned_tag" compose_run build --no-cache
    $RUNTIME tag "geodatalab:${versioned_tag}" "geodatalab:latest" 2>/dev/null || true
    IMAGE_TAG="$versioned_tag"
    save_config
    if container_is_running; then
        info "Restarting with new image..."
        compose_run up -d
    fi
    info "Update complete."
    $RUNTIME images --filter "reference=geodatalab" \
        --format "  {{.Tag}}  {{.Size}}" 2>/dev/null | head -8 || true
}

# Regenerate .gdl/<instance>/compose.data.yml without starting anything (used by
# .devcontainer/devcontainer.json's initializeCommand).
container_render() {
    container_render_data
    info "Rendered ${COMPOSE_DATA_FILE#"${SCRIPT_DIR}"/}"
}
