"""Render an instance into what a backend needs: the compose fragment
(container) or the linked workbench root (pixi). Workbenches get the same
layout on every backend:

    $GDL_ROOT/workspace      -> workspace (read-write)    GDL_WORKSPACE
    $GDL_ROOT/data/<name>    -> each data folder           GDL_DATA, GDL_DATA_<NAME>

plus GDL_SERVICE_<NAME> = the connection URL of each service instance.
All containers join one network (NETWORK), where an instance is reachable by
its name, e.g. postgresql://...@gisdb:5432/gis from a container workbench.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

from .config import ROOT, GdlError, Instance, Settings

SERVICE = "gis"
CONTAINER_ROOT = "/gdl"
NETWORK = "geodatalab"


def q(value) -> str:
    """YAML double-quoted scalar ($ escaped: compose would interpolate it)."""
    return json.dumps(str(value).replace("$", "$$"))


def data_var(name: str) -> str:
    return "GDL_DATA_" + name.upper().replace("-", "_")


def service_var(name: str) -> str:
    return "GDL_SERVICE_" + name.upper().replace("-", "_")


def service_url(inst: Instance, internal: bool = False) -> str:
    """How to reach a service: from this machine (localhost:<host port>) or,
    internal=True, from another container on the network (<name>:<port>)."""
    from .templates import get
    t = get(inst.template)
    host, port = (inst.name, t.port) if internal else ("localhost", inst.port)
    return t.fill(t.url, inst.env, host=host, port=port) if t.url else f"{host}:{port}"


def service_urls(settings: Settings, internal: bool) -> dict[str, str]:
    """GDL_SERVICE_<NAME> -> URL for every service instance (broken templates skipped)."""
    urls = {}
    for n in settings.names():
        inst = settings.get(n)
        if inst.is_service:
            try:
                urls[service_var(n)] = service_url(inst, internal)
            except GdlError:
                pass
    return urls


def gdl_env(inst: Instance, root: str, services: dict[str, str] | None = None) -> dict[str, str]:
    env = {
        "GDL_ROOT": root,
        "GDL_WORKSPACE": f"{root}/workspace",
        "GDL_DATA": f"{root}/data",
        "GDL_OPEN": inst.open,
        "GDL_PROFILE": inst.profile,
        "GDL_BACKEND": inst.backend,
        "GDL_INSTANCE": inst.name,
    }
    env.update({data_var(d.name): f"{root}/data/{d.name}" for d in inst.data})
    env.update(services or {})
    env.update(inst.env)
    return env


def image(inst: Instance) -> str:
    return inst.image if inst.is_service else f"geodatalab:{inst.image_tag or 'latest'}"


def _common(inst: Instance, env: dict[str, str], mounts: list[tuple[str, str, str, bool]]) -> list[str]:
    """The service body shared by workbenches and services."""
    out = [
        f"    image: {q(image(inst))}",
        f"    container_name: {q(inst.container_name)}",
        "    labels:",
        f"      - {q(f'io.geodatalab.checkout={ROOT}')}",
        f"      - {q(f'io.geodatalab.instance={inst.name}')}",
        "    environment:",
        *(f"      - {q(f'{k}={v}')}" for k, v in env.items()),
    ]
    if mounts:
        out.append("    volumes:")
        for kind, src, dst, ro in mounts:  # kind: bind (host folder) | volume (named)
            out += [f"      - type: {kind}", f"        source: {q(src)}", f"        target: {q(dst)}"]
            if ro:
                out.append("        read_only: true")
    if inst.shm_size:
        out.append(f"    shm_size: {q(inst.shm_size)}")
    if inst.memory or inst.cpus or inst.memory_reserve:
        out += ["    deploy:", "      resources:"]
        if inst.memory or inst.cpus:
            out.append("        limits:")
            if inst.memory:
                out.append(f"          memory: {q(inst.memory)}")
            if inst.cpus:
                out.append(f"          cpus: {q(inst.cpus)}")
        if inst.memory_reserve:
            out += ["        reservations:", f"          memory: {q(inst.memory_reserve)}"]
    out += ["    networks:", "      default:", f"        aliases: [{q(inst.name)}]"]
    return out


_HEADER = ["# GENERATED by geodatalab for instance '{name}' — do not edit, changes are overwritten.",
           "# Manage with: pixi run gdl  (or edit geodatalab.toml)"]
_NETWORK = ["networks:", "  default:", f"    name: {q(NETWORK)}", "    external: true"]


def compose_fragment(inst: Instance, services: dict[str, str] | None = None) -> str:
    """Workbench: self-contained override of compose.yml (no ${VAR}
    interpolation), also used by .devcontainer. Long volume syntax, so Windows
    paths (C:\\...) work. No :Z relabel: compose.yml sets label=disable."""
    if inst.is_service:
        return service_fragment(inst)
    env = {"GDL_MODE": inst.mode, **gdl_env(inst, CONTAINER_ROOT, services)}
    for k in ("GDL_ROOT", "GDL_WORKSPACE", "GDL_DATA"):  # fixed, set in compose.yml
        del env[k]
    mounts = [("bind", inst.workspace, f"{CONTAINER_ROOT}/workspace", False)] if inst.workspace else []
    mounts += [("bind", d.path, f"{CONTAINER_ROOT}/data/{d.name}", d.ro) for d in inst.data]
    out = [h.format(name=inst.name) for h in _HEADER] + ["services:", f"  {SERVICE}:"]
    out += _common(inst, env, mounts) + _NETWORK
    return "\n".join(out) + "\n"


def service_fragment(inst: Instance) -> str:
    """Service (from a template): a complete compose file on its own."""
    from .templates import get
    t = get(inst.template)
    env = {"GDL_INSTANCE": inst.name, **inst.env}
    mounts = [("volume", "data", t.volume, False)] if t.volume else []
    mounts += [("bind", d.path, f"{CONTAINER_ROOT}/data/{d.name}", d.ro) for d in inst.data]
    out = [h.format(name=inst.name) for h in _HEADER] + ["services:", f"  {inst.template}:"]
    out += _common(inst, env, mounts)
    out += ["    restart: unless-stopped", "    ports:",
            f"      - {q(f'127.0.0.1:{inst.port}:{t.port}')}"]
    if t.health:
        out += ["    healthcheck:", f"      test: [\"CMD-SHELL\", {q(t.fill(t.health, inst.env))}]",
                "      interval: 10s", "      timeout: 5s", "      retries: 5", "      start_period: 20s"]
    if t.volume:
        out += ["volumes:", "  data:", f"    name: {q(inst.container_name + '-data')}"]
    return "\n".join(out + _NETWORK) + "\n"


def write_fragment(inst: Instance, services: dict[str, str] | None = None) -> Path:
    path = inst.state_dir / "compose.data.yml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(compose_fragment(inst, services), encoding="utf-8")
    return path


# ── Linked workbench root (host-process backends) ─────────────────────────────
# Only links are ever created or removed here — never real files or folders.
# POSIX: symlinks. Windows: directory junctions (no admin rights needed).

def is_link(p: Path) -> bool:
    return p.is_symlink() or (sys.platform == "win32" and p.is_junction())


def unlink(p: Path) -> None:
    if p.is_junction():
        os.rmdir(p)  # removes the junction only, never the target
    else:
        p.unlink()


def link(target: str, p: Path) -> None:
    if p.exists() or is_link(p):
        if not is_link(p):
            raise GdlError(f"{p} exists and is not a link — refusing to touch it.")
        unlink(p)
    if sys.platform == "win32":
        import _winapi
        _winapi.CreateJunction(str(Path(target).resolve()), str(p))
    else:
        os.symlink(target, p, target_is_directory=True)


def build_root(inst: Instance) -> tuple[Path, list[str]]:
    """(Re)build .gdl/<instance>/root. Returns (root, warnings)."""
    root = inst.state_dir / "root"
    (root / "data").mkdir(parents=True, exist_ok=True)
    warnings = []
    link(inst.workspace, root / "workspace")
    for p in (root / "data").iterdir():
        if is_link(p):
            unlink(p)
    for d in inst.data:
        if not Path(d.path).is_dir():
            warnings.append(f"Data folder '{d.name}' missing: {d.path} (linked anyway)")
            if sys.platform == "win32":
                continue  # a junction needs an existing target
        link(d.path, root / "data" / d.name)
    if any(d.ro for d in inst.data):
        warnings.append("Read-only data folders are not enforced on the pixi backend.")
    return root, warnings


def remove_state(inst: Instance) -> None:
    """Delete .gdl/<instance>: links first (never following them), then the rest."""
    import shutil
    if not inst.state_dir.exists():
        return
    for dirpath, dirnames, filenames in os.walk(inst.state_dir):
        for n in dirnames + filenames:
            p = Path(dirpath) / n
            if is_link(p):
                unlink(p)
    shutil.rmtree(inst.state_dir)
