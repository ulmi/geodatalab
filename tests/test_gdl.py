                 {"pid": 20, "ppid": 10, "cpu": 2.0, "rss": 200, "threads": 9, "kernel": kid},     # kernel
                 {"pid": 21, "ppid": 20, "cpu": 99.0, "rss": 50, "threads": 1, "kernel": kid},     # forked worker
