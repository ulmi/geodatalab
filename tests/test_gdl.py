class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.toml = self.tmp / "geodatalab.toml"
        patches = [mock.patch.dict(os.environ, {"GDL_CONFIG": str(self.toml)}),
                   mock.patch.object(config, "STATE_ROOT", self.tmp / ".gdl"),
                   mock.patch.object(config, "port_open", lambda p: False)]
        for p in patches:
            p.start()
            self.addCleanup(p.stop)
        os.environ.pop("GDL_BACKEND", None)

    def legacy(self, text=LEGACY, instances=None):
        (self.tmp / ".geodatalab").write_text(text)
        for name, body in (instances or {}).items():
            (self.tmp / ".geodatalab.d").mkdir(exist_ok=True)
            (self.tmp / ".geodatalab.d" / name).write_text(body)
        self.assertTrue(config.migrate_legacy(self.tmp, self.toml))
        return Settings(self.toml)


class TestMigration(Base):
    def test_values(self):
        i = self.legacy().get()
        self.assertEqual((i.backend, i.mode, i.port, i.image_tag), ("container", "lab", 8890, "2026.11-lab"))
        self.assertEqual(i.data, [DataDir("ccdrn", "/media/disk1/CCDRN", True),
                                  DataDir("my-data", "/srv/with space", False)])
        self.assertEqual((i.memory, i.memory_reserve, i.cpus), ("56G", "4G", "6"))

    def test_old_files_kept_once(self):
        self.legacy(instances={"pinhel": "GDL_PORT=8891\nPROFILE=kitchen\n"})
        self.assertTrue((self.tmp / ".geodatalab.bak").exists())
        self.assertTrue((self.tmp / ".geodatalab.d.bak" / "pinhel").exists())
        self.assertFalse(config.migrate_legacy(self.tmp, self.toml))  # already done

    def test_instance_overlay(self):
        s = self.legacy(instances={"pinhel": "GDL_PORT=8891\nPROFILE=kitchen\n"})
        p = s.get("pinhel")
        self.assertEqual((p.port, p.profile, p.workspace), (8891, "kitchen", "/home/u/projects"))
        self.assertEqual(p.container_name, "geodatalab-pinhel")

    def test_real_old_checkout_config(self):  # the format of geodatalab's first release
        i = self.legacy('WORKSPACE="/mnt/x/teste"\nPROFILE="lab"\nGDL_MODE="lab"\n'
                        'GDL_PORT="8888"\nIMAGE_TAG="2026.06-lab"\n').get()
        self.assertEqual((i.workspace, i.backend, i.image_tag), ("/mnt/x/teste", "container", "2026.06-lab"))


class TestSettings(Base):
    def test_instance_stores_only_differences(self):
        s = Settings(self.toml)
        s.update(s.get(), workspace="/w", profile="lab")
        p = s.new_instance("pinhel")
        self.assertEqual(p.port, 8889)  # 8888 is taken by default
        s.update(p, profile="kitchen", workspace="/w")
        self.assertEqual(Settings(self.toml).instances["pinhel"], {"port": 8889, "profile": "kitchen"})

    def test_round_trip(self):
        s = Settings(self.toml)
        s.update(s.get(), memory="8G", data=[DataDir("a", "/a", True)])
        i = Settings(self.toml).get()
        self.assertEqual((i.memory, i.data), ("8G", [DataDir("a", "/a", True)]))
        self.assertIn("[limits]", self.toml.read_text())

    def test_delete_default(self):
        s = Settings(self.toml)
        s.update(config.Instance(), workspace="/w", profile="lab", memory="8G")
        s.new_instance("pinhel")
        s.update(s.get("pinhel"), profile="kitchen")
        s.remove_instance("default")
        s = Settings(self.toml)
        self.assertEqual(s.names(), ["pinhel"])
        p = s.get("pinhel")  # kept what it inherited
        self.assertEqual((p.workspace, p.profile, p.memory, p.port), ("/w", "kitchen", "8G", 8889))
        with self.assertRaises(GdlError):
            s.get("default")
        d = s.new_instance("default")  # can be recreated
        self.assertEqual(s.names(), ["default", "pinhel"])
        self.assertEqual(d.port, 8888)

    def test_delete_everything(self):
        s = Settings(self.toml)
        s.update(config.Instance(), workspace="/w")
        s.remove_instance("default")
        self.assertEqual(Settings(self.toml).names(), [])

    def test_validation(self):
        s = Settings(self.toml)
        s.update(config.Instance(), workspace="/w")
        for bad in ("default", "Bad", "-x"):
            with self.assertRaises(GdlError):
                s.new_instance(bad)
        with self.assertRaises(GdlError):
            s.get("missing")
        with self.assertRaises(GdlError):
            config.check_data_name("dirs", [])


class TestRender(Base):
    def test_fragment_matches_bash(self):
        i = self.legacy().get()
        self.assertEqual(render.compose_fragment(i), EXPECTED_FRAGMENT.format(root=config.ROOT))

    def test_windows_path_is_one_scalar(self):
        i = config.Instance(workspace="C:\\Users\\me\\proj")
        self.assertIn('source: "C:\\\\Users\\\\me\\\\proj"', render.compose_fragment(i))

    def test_root_links(self):
        ws, data = self.tmp / "ws", self.tmp / "d1"
        ws.mkdir(), data.mkdir()
        i = config.Instance(workspace=str(ws), data=[DataDir("d1", str(data)), DataDir("gone", str(self.tmp / "x"))])
        root, warnings = render.build_root(i)
        self.assertTrue(render.is_link(root / "workspace"))
        self.assertEqual((root / "data" / "d1").resolve(), data.resolve())
        self.assertTrue(any("gone" in w for w in warnings))
        (ws / "keep.txt").write_text("x")
        i.data = []
        render.build_root(i)  # stale links go, targets stay
        self.assertFalse((root / "data" / "d1").exists())
        self.assertTrue(data.is_dir())
        render.remove_state(i)
        self.assertFalse(i.state_dir.exists())
        self.assertTrue((ws / "keep.txt").exists())

    def test_refuses_real_folder(self):
        i = config.Instance(workspace=str(self.tmp))
        (i.state_dir / "root" / "workspace").mkdir(parents=True)
        with self.assertRaises(GdlError):
            render.build_root(i)


class TestServices(Base):
    def setUp(self):
        super().setUp()
        self.s = Settings(self.toml)
        self.s.update(config.Instance(), workspace="/w", backend="pixi")

    def test_template_loads(self):
        from gdl import templates
        t = templates.get("postgis")
        self.assertEqual((t.port, list(t.images)), (5432, ["debian", "alpine"]))
        with self.assertRaises(GdlError):
            templates.get("nope")

    def test_new_service(self):
        db = self.s.new_instance("gisdb", "postgis")
        self.assertTrue(db.is_service)
        self.assertEqual((db.backend, db.port, db.shm_size), ("container", 5432, "1g"))
        self.assertEqual(db.env["POSTGRES_USER"], "gis")
        self.assertGreater(len(db.env["POSTGRES_PASSWORD"]), 16)
        self.assertEqual(self.s.new_instance("db2", "postgis").port, 5433)  # next free
        alpine = self.s.new_instance("db3", "postgis", "alpine")
        self.assertTrue(alpine.image.endswith("-alpine"))
        with mock.patch.dict(os.environ, {"GDL_BACKEND": "pixi"}):
            self.assertEqual(Settings(self.toml).get("gisdb").backend, "container")
        with self.assertRaises(GdlError):
            self.s.new_instance("db4", "postgis", "nope")

    def test_workbench_after_service_default(self):
        self.s.remove_instance("default")
        self.s.new_instance("default", "postgis")
        wb = self.s.new_instance("wb")
        self.assertFalse(wb.is_service)
        self.assertEqual((wb.env, wb.image, wb.port), ({}, "", 8888))

    def test_service_fragment(self):
        db = self.s.new_instance("gisdb", "postgis")
        db = self.s.update(db, env={**db.env, "POSTGRES_PASSWORD": "pa$$"})
        f = render.compose_fragment(db)
        for want in ['image: "docker.io/postgis/postgis:17-3.5"', 'container_name: "geodatalab-gisdb"',
                     '- "127.0.0.1:5432:5432"', 'shm_size: "1g"', 'aliases: ["gisdb"]',
                     'test: ["CMD-SHELL", "pg_isready -U gis -d gis"]',
                     'name: "geodatalab-gisdb-data"', 'target: "/var/lib/postgresql/data"',
                     '- "POSTGRES_PASSWORD=pa$$$$"',  # $ escaped for compose
                     'name: "geodatalab"', "external: true"]:
            self.assertIn(want, f)
        self.assertNotIn("GDL_MODE", f)

    def test_connections(self):
        db = self.s.new_instance("gisdb", "postgis")
        pw = db.env["POSTGRES_PASSWORD"]
        self.assertEqual(render.service_url(db), f"postgresql://gis:{pw}@localhost:5432/gis")
        self.assertEqual(render.service_url(db, internal=True), f"postgresql://gis:{pw}@gisdb:5432/gis")
        # container workbench: internal address in its compose fragment
        wb = self.s.get()
        frag = render.compose_fragment(wb, render.service_urls(self.s, internal=True))
        self.assertIn(f'"GDL_SERVICE_GISDB=postgresql://gis:{pw}@gisdb:5432/gis"', frag)
        # pixi workbench: localhost address in its environment
        env = render.gdl_env(wb, "/root", render.service_urls(self.s, internal=False))
        self.assertEqual(env["GDL_SERVICE_GISDB"], f"postgresql://gis:{pw}@localhost:5432/gis")


