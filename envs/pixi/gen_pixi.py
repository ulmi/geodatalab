#!/usr/bin/env python3
"""Generate pixi.toml (repo root) from the geodatalab profiles.

Single source of truth: requirements/<profile>.txt — the same files the
container image installs with pip — plus envs/pixi/native.txt for packages
that are not on PyPI (gdal, pdal, grass, r-base, julia...). Python packages map
1:1 to conda-forge names except for the few listed in RENAME / PYPI_ONLY.

    gen_pixi.py            write ../../pixi.toml
    gen_pixi.py --check    exit 1 if pixi.toml is out of date
    gen_pixi.py --stdout   print instead of writing

One pixi environment per profile (pixi names: r+julia -> r-julia).
Stdlib only, so it runs on any host python3.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
REQ_DIR = ROOT / "requirements"
NATIVE = HERE / "native.txt"
OUT = ROOT / "pixi.toml"

PYTHON = "3.13.*"  # keep in sync with GDL_PYTHON in lib/common.sh (trixie python3)
PROFILES = ["kitchen", "lab", "institute", "r+julia"]
PLATFORMS = ["linux-64"]  # add "linux-aarch64", "osx-arm64" ... when needed

# pip name (normalised) -> conda-forge name
RENAME = {
    "pdal": "python-pdal",
    "matplotlib": "matplotlib-base",  # headless: skip the Qt/PySide6 GUI backend
}
# Not on conda-forge: installed from PyPI by pixi (uv) inside the env
PYPI_ONLY = {
    "whitebox-workflows",
}


def env_name(profile: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", profile.lower())


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_requirements(path: Path, seen: set[Path] | None = None) -> list[str]:
    seen = seen or set()
    if path in seen:
        return []
    seen.add(path)
    out: list[str] = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-r "):
            out += read_requirements(path.parent / line[3:].strip(), seen)
        else:
            out.append(line)
    return out


def read_native() -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current = None
    for raw in NATIVE.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"\[(.+)\]", line)
        if m:
            current = m.group(1)
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return sections


def expand_native(sections: dict[str, list[str]], name: str, stack: tuple[str, ...] = ()) -> list[str]:
    if name not in sections:
        sys.exit(f"gen_pixi.py: no section [{name}] in {NATIVE}")
    if name in stack:
        sys.exit(f"gen_pixi.py: include cycle {' -> '.join(stack + (name,))}")
    pkgs: list[str] = []
    for item in sections[name]:
        pkgs += expand_native(sections, item[1:], stack + (name,)) if item.startswith("@") else [item]
    return pkgs


def split_name(spec: str) -> tuple[str, str]:
    m = re.match(r"([A-Za-z0-9_.\-]+)(.*)", spec)
    if not m:
        sys.exit(f"gen_pixi.py: cannot parse requirement {spec!r}")
    return m.group(1), m.group(2).strip()


def conda_dep(name: str, rest: str) -> str:
    """name + conda match-spec tail ('', '>=1', '=1.2', '=*=cpu*') -> TOML line."""
    if rest.startswith("=") and not rest.startswith("=="):
        parts = rest[1:].split("=", 1)
        ver = parts[0] or "*"
        if len(parts) == 2:
            return f'{name} = {{ version = "{ver}", build = "{parts[1]}" }}'
        return f'{name} = "{ver}"'
    return f'{name} = "{rest.replace("==", "") or "*"}"'


def render() -> str:
    native = read_native()
    lines = [
        "# GENERATED by envs/pixi/gen_pixi.py from requirements/*.txt and",
        "# envs/pixi/native.txt — do not edit; regenerate + re-lock: ./geodatalab.sh lock",
        "#",
        "# Usable without the CLI too:  pixi run -e lab jupyter lab",
        "",
        "[workspace]",
        'name = "geodatalab"',
        'channels = ["conda-forge"]',
        "platforms = [" + ", ".join(f'"{p}"' for p in PLATFORMS) + "]",
        "",
        "[dependencies]",
        f'python = "{PYTHON}"',
        'pip = "*"',
    ]
    envs = []
    for profile in PROFILES:
        feat = env_name(profile)
        conda: dict[str, str] = {}
        pypi: dict[str, str] = {}
        for entry in expand_native(native, profile):
            name, rest = split_name(entry)
            conda[name] = conda_dep(name, rest)
        for spec in read_requirements(REQ_DIR / f"{profile}.txt"):
            raw, rest = split_name(spec)
            name = norm(raw)
            if name in PYPI_ONLY:
                pypi[name] = f'{name} = "{rest or "*"}"'
            else:
                cname = RENAME.get(name, name)
                conda[cname] = conda_dep(cname, rest)
        lines += ["", f"[feature.{feat}.dependencies]", *conda.values()]
        if pypi:
            lines += ["", f"[feature.{feat}.pypi-dependencies]", *pypi.values()]
        envs.append(f'{feat} = {{ features = ["{feat}"] }}')
    lines += ["", "[environments]", *envs, ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--stdout" in argv:
        print(text, end="")
        return 0
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        return 0 if current == text else 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
